package dev.cannoli.scorza.launcher

import androidx.test.core.app.ApplicationProvider
import dev.cannoli.scorza.config.CoreInfoRepository
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class ContentSupportTest {

    private val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
    private val repo = CoreInfoRepository(ctx.assets).also { it.load() }

    private fun dir(name: String) =
        File(ctx.cacheDir, name).apply { deleteRecursively(); mkdirs() }

    private fun rom(d: File, name: String) = File(d, name).apply { writeText("x") }

    private fun zip(d: File, name: String, vararg inner: String) = File(d, name).apply {
        ZipOutputStream(outputStream()).use { zos ->
            inner.forEach {
                zos.putNextEntry(ZipEntry(it))
                zos.write(ByteArray(64) { 1 })
                zos.closeEntry()
            }
        }
    }

    private fun m3u(d: File, name: String, vararg lines: String) =
        File(d, name).apply { writeText(lines.joinToString("\n") + "\n") }

    private fun check(file: File, core: String) =
        ContentSupport.unsupported(file, repo.getExtensionsFor(core))

    @Test fun `a romset handed to a disc only core`() {
        val d = dir("cs-pcfx")
        assertEquals("zip", check(zip(d, "lbowling.zip", "lbowling/202-c1.c1"), "mednafen_pcfx_libretro"))
    }

    @Test fun `the same file on FinalBurn Neo is fine`() {
        val d = dir("cs-fbneo")
        assertNull(check(zip(d, "lbowling.zip", "lbowling/202-c1.c1"), "fbneo_libretro"))
    }

    @Test fun `a zipped ROM passes on a core that declares no archive format`() {
        val d = dir("cs-zipped")
        assertNull(check(zip(d, "Mario.zip", "Mario.sfc"), "snes9x_libretro"))
    }

    @Test fun `a plain ROM the core does declare passes`() {
        val d = dir("cs-plain")
        assertNull(check(rom(d, "Mario.sfc"), "snes9x_libretro"))
    }

    @Test fun `a plain ROM for the wrong core is refused`() {
        val d = dir("cs-wrong")
        assertEquals("sfc", check(rom(d, "Mario.sfc"), "gambatte_libretro"))
    }

    @Test fun `multi-disc m3u passes on cores that never declare m3u`() {
        val d = dir("cs-m3u")
        val playlist = m3u(d, "FF7.m3u", "FF7 (Disc 1).cue", "FF7 (Disc 2).cue")
        for (core in listOf("yabasanshiro_libretro", "swanstation_libretro")) {
            assertNull("$core refused a multi-disc playlist", check(playlist, core))
        }
    }

    @Test fun `an m3u passes on a core that does declare m3u`() {
        val d = dir("cs-m3u-declared")
        assertNull(check(m3u(d, "FF7.m3u", "FF7 (Disc 1).cue"), "pcsx_rearmed_libretro"))
    }

    @Test fun `an m3u of unreadable discs is refused`() {
        val d = dir("cs-m3u-bad")
        assertEquals("m3u", check(m3u(d, "Game.m3u", "Game (Disc 1).sfc"), "pcsx_rearmed_libretro"))
    }

    @Test fun `comments and blank lines are not the first entry`() {
        val d = dir("cs-m3u-comments")
        val playlist = m3u(d, "FF7.m3u", "# generated by Cannoli", "", "FF7 (Disc 1).cue")
        assertNull(check(playlist, "yabasanshiro_libretro"))
    }

    @Test fun `declared formats keep the order the info gives them`() {
        assertEquals(listOf("cue", "ccd", "toc", "chd"), repo.getExtensionsFor("mednafen_pcfx_libretro"))
        assertEquals(listOf("zip", "7z", "cue", "ccd"), repo.getExtensionsFor("fbneo_libretro"))
    }

    @Test fun `a trailing separator does not become an empty format`() {
        for (core in listOf("puae_libretro", "dosbox_pure_libretro")) {
            val exts = repo.getExtensionsFor(core)
            assertEquals("$core has a blank format", emptyList<String>(), exts.filter { it.isBlank() })
        }
    }

    @Test fun `a core that declares nothing never refuses`() {
        val d = dir("cs-unknown")
        assertNull(ContentSupport.unsupported(rom(d, "Mario.sfc"), emptySet()))
    }

    @Test fun `an unreadable archive is let through`() {
        val d = dir("cs-corrupt")
        assertNull(check(rom(d, "broken.zip"), "mednafen_pcfx_libretro"))
    }

    @Test fun `an extensionless file is let through`() {
        val d = dir("cs-noext")
        assertNull(check(rom(d, "Mario"), "snes9x_libretro"))
    }
}
